/**
 * 품질 검사. 크로스워드 힌트와 퀴즈 문제가 함께 쓴다.
 *
 * 안전 검사(lib/safety.js)가 «나가면 안 되는 말» 을 본다면, 여기는 «문제가 되는가» 를 본다.
 *   · 정답이 문제에 새지 않았는가
 *   · 길이가 읽을 만한가
 *   · 실력 없는 사람도 풀 수 있는가 (약한 모델에게 보기를 주고 고르게 해 본다)
 *
 * 왜 한 군데 두나
 *   같은 흠이 양쪽에서 났다.
 *   크로스워드 — «재판소원» 힌트에 «재판소원» 이 그대로 들어 있었다.
 *   퀴즈      — «쿠팡의 지분을 보유한 법인은?» 의 답이 «쿠팡Inc» 였다.
 *   규칙을 양쪽에 따로 적어 두면 한쪽만 고치고 다른 쪽은 잊는다.
 *
 * 풀어 보게 하는 쪽은 약한 모델(Haiku)을 쓴다.
 * 좋은 모델이 푸는 시험은 어려운 것도 통과시켜 버려 쉬운지를 가리지 못한다.
 */

/* 몇 음절까지 봐주나.
   크로스워드는 두 음절까지 봐준다 — «유럽연합» 힌트에 «유럽» 도 못 쓰면
   «큰 대륙의 모임» 같은 두루뭉술한 말밖에 안 남고, 그렇게 어려워진 낱말을 여럿 뺐다.
   퀴즈도 같다 — «유럽» 을 물어 «유럽연합» 을 답하게 하는 것은 괜찮다.
   따로 잡는 것은 «이름 + 흔한 꼬리» 뿐이다. «쿠팡의 지분을 보유한 법인은?» 의 답이
   «쿠팡Inc» 이면 이름을 통째로 보여 주고 꼬리만 맞히라는 셈이라 문제가 아니다. */
const 봐주는길이 = { 크로스워드: 2, 퀴즈: 2 };

/** 회사·기관 이름 뒤에 흔히 붙는 꼬리. 이것만 뗀 나머지가 글에 있으면 답을 보여 준 것이다 */
const 흔한꼬리 = /(Inc\.?|Corp\.?|Ltd\.?|LLC|㈜|주식회사|주식|그룹|재단|법인|사|본부|지부)$/i;

/**
 * 정답이 글에 샜는가.
 * @param {string} 정답
 * @param {string} 글
 * @param {{봐주기?: number}} 옵션  봐주기 = 이 길이까지는 겹쳐도 넘어간다
 * @returns {{샘: boolean, 어디: string}} 어디 = 샌 토막(없으면 '')
 */
function 누설(정답, 글, { 봐주기 = 봐주는길이.크로스워드 } = {}) {
  const a = String(정답 || '').replace(/\s+/g, '');
  const t = String(글 || '').replace(/\s+/g, '');
  if (!a || !t) return { 샘: false, 어디: '' };
  if (t.includes(a)) return { 샘: true, 어디: a };
  // 이름에 흔한 꼬리만 붙은 답 — 꼬리를 뗀 이름이 글에 있으면 답을 보여 준 것이다
  const 꼬리뗀 = a.replace(흔한꼬리, '');
  if (꼬리뗀.length >= 2 && 꼬리뗀 !== a && t.includes(꼬리뗀)) return { 샘: true, 어디: 꼬리뗀 };
  for (let i = 0; i + 봐주기 + 1 <= a.length; i++) {
    const 토막 = a.slice(i, i + 봐주기 + 1);
    if (t.includes(토막)) return { 샘: true, 어디: 토막 };
  }
  return { 샘: false, 어디: '' };
}

/** 길이가 읽을 만한가 */
function 길이(글, { 최대 = 60, 최소 = 6 } = {}) {
  const n = String(글 || '').length;
  return { 맞나: n >= 최소 && n <= 최대, 글자수: n };
}

/**
 * 보기를 만든다 — 정답 하나와 다른 후보 넷. 글자 수가 비슷한 것으로 고른다.
 * @param {string} 정답
 * @param {string[]} 후보들  단어장이나 개체 목록
 */
function 보기만들기(정답, 후보들, 개수 = 5) {
  const 또래 = 후보들.filter(c => c !== 정답 && Math.abs(c.length - 정답.length) <= 1);
  const 뽑은 = [];
  const 쓴것 = new Set();
  while (뽑은.length < 개수 - 1 && 또래.length) {
    const c = 또래[Math.floor(Math.random() * 또래.length)];
    if (!쓴것.has(c)) { 쓴것.add(c); 뽑은.push(c); }
    if (쓴것.size >= 또래.length) break;
  }
  return [정답, ...뽑은].sort(() => Math.random() - 0.5);
}

/**
 * 풀어 보게 하는 물음. 정답을 알려 주지 않고 보기에서 고르게 한다.
 * 낱말을 몰라도 글이 제대로 가리키면 고를 수 있다 —
 * 공소청·중대범죄수사청처럼 모델이 배운 뒤에 생긴 말도 이 방식이면 시험이 된다.
 * @param {{글: string, 보기: string[]}[]} 문항들
 */
function 풀림물음(문항들) {
  return `아래 글이 가리키는 것을 보기에서 고른다.

처음 들어 보는 말이어도 괜찮다. 글이 가리키는 쪽을 고르면 된다.
고를 수 없을 만큼 글이 흐릿하면 «못고름» 이라고 적는다.

한 줄에 하나씩 "번호|고른것" 꼴로만 적는다. 다른 말은 쓰지 않는다.

${문항들.map((x, i) => `${i + 1}. ${x.글}\n   보기: ${x.보기.join(' / ')}`).join('\n')}`;
}

/** 풀림 응답을 읽는다 → Map(번호 → 고른것) */
function 풀림읽기(글) {
  const out = new Map();
  for (const line of String(글 || '').split(/\r?\n/)) {
    const m = line.match(/^\s*(\d+)\s*[.|]\s*(.+?)\s*$/);
    if (m) out.set(Number(m[1]), m[2].replace(/\s+/g, ''));
  }
  return out;
}

/**
 * 사실을 보는 물음. 기사 대목을 함께 주되, 모르는 것은 «모름» 으로 답하게 한다 —
 * 모르는 말을 틀렸다고 하면 새 말이 다 걸린다.
 * @param {{이름: string, 글: string, 대목?: string[]}[]} 문항들
 */
function 사실물음(문항들) {
  return `아래 글에 사실과 어긋나는 데가 있는지 본다.
기사 대목을 함께 주되, 기사에 없는 것도 아는 상식으로 판단한다.
처음 들어 보는 말이면 «모름» 이라고 적는다 — 모르는 것을 틀렸다고 하지 않는다.

한 줄에 하나씩 "이름|맞음" / "이름|틀림|무엇이 틀렸는지" / "이름|모름" 꼴로만 적는다.

${문항들.map(x => `[${x.이름}] ${x.글}${(x.대목 || []).map(e => `\n   기사: ${e}`).join('')}`).join('\n\n')}`;
}

/** 사실 응답을 읽는다 → Map(이름 → {판정, 까닭}) */
function 사실읽기(글) {
  const out = new Map();
  for (const line of String(글 || '').split(/\r?\n/)) {
    const m = line.match(/^\s*(.+?)\s*\|\s*(맞음|틀림|모름)\s*\|?\s*(.*)$/);
    if (m) out.set(m[1].trim(), { 판정: m[2], 까닭: m[3] || '' });
  }
  return out;
}

/** 크로스워드 힌트·퀴즈 문제가 함께 쓰는 마지막 관문. 안전 검사와 나란히 선다 */
function 성한가(정답, 글, 옵션 = {}) {
  const l = 길이(글, 옵션);
  if (!l.맞나) return { 성함: false, 까닭: `길이 ${l.글자수}자` };
  const n = 누설(정답, 글, 옵션);
  if (n.샘) return { 성함: false, 까닭: `정답이 샘 (${n.어디})` };
  return { 성함: true, 까닭: '' };
}

module.exports = { 누설, 길이, 보기만들기, 풀림물음, 풀림읽기, 사실물음, 사실읽기, 성한가, 봐주는길이 };
