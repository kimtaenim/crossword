/** 검사 응답을 읽는다 → Map(이름 → {답, 까닭}) */
function 판정읽기(글) {
  const out = new Map();
  for (const line of String(글 || '').split(/\r?\n/)) {
    const m = line.match(/^\s*(.+?)\s*\|\s*(괜찮음|고칠것)\s*\|?\s*(.*)$/);
    if (m) out.set(m[1].trim().replace(/^\[|\]$/g, ''), { 답: m[2], 까닭: m[3] || '' });   // «[낱말]|…» 로 답해도 읽는다
  }
  return out;
}

