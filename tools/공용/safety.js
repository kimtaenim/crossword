/** 기사 대목을 붙여 «그 사안을 다루는 글인가, 다른 말의 예로 끌어다 썼는가» 를 묻는다 */
function 맥락물음(묶음) {
  return `시사 주간지가 내보낼 글에 역사·외교로 다투는 사안이 들어 있다.
그 사안을 «다루는» 글이면 괜찮다. 다른 낱말을 설명하려고 «예» 로 끌어다 쓴 것이면 고쳐야 한다.
(사도광산 등재를 «인류에게 값진 문화재» 의 예로 들면, 강제동원을 두고 다투는 일을 받아들인 것처럼 읽힌다)

한 줄에 하나씩 "이름|괜찮음" 또는 "이름|고칠것|까닭 한 구절" 꼴로만 적는다.

${묶음.map(x => `[${x.이름}] ${x.글}${(x.대목 || []).map(e => `\n   기사: ${e}`).join('')}`).join('\n\n')}`;
}

/* ── 곁가지 꼴: «[어디서 나왔나], [무엇인가]» ──────────────────────
   기사 한 건에 그 말이 한 번 스쳤다고 앞에 붙인 맥락이 힌트를 망쳤다 —
   «양극화 — 경찰 개혁 논의에서 나온, …», «지자체 — 가난한 노인의 개를 빼앗은 일에서 나온, …».
   이 꼴은 사람이 보고 적어 둔 것(살펴본말)만 나간다. */
const 곁가지꼴 = /(에서|속에서?|이후|뒤로도|앞두고|과정에서|때처럼)\s*(나온|언급된|거론된|거론되는|떠오른|도마에 오른|불거진|드러난|주목받은|주목된|다뤄진|나타난|부과된|제기된|화제가 된|논란이 된|등장한)\s*,?/;

/** 뉴스 곁가지를 앞에 붙인 꼴인가 */
function 곁가지(글) {
  const m = String(글 || '').match(곁가지꼴);
  return { 붙음: Boolean(m), 어디: m ? m[0] : '' };
}

/* ── 한 번에: 3겹을 모두 돌린다 ───────────────────────────────
   크로스워드 도구들과 퀴즈가 저마다 물음을 짜면 한쪽만 느슨해진다. 여기 하나를 부른다.
   부르기(물음) → 모델의 답 글. 쓴 모델과 다른 모델을 부르게 한다(부르는 쪽이 정한다).
   걸린 것만 Map(이름 → 까닭들) 으로 돌려준다. 2겹(기계 목록)도 여기서 같이 본다. */
async function 모델검사(묶음, 부르기) {
  const 걸림 = new Map();
  const 적기 = (이름, 까닭) => { if (!걸림.has(이름)) 걸림.set(이름, []); 걸림.get(이름).push(까닭); };
  for (const x of 묶음) {
    const r = 검사(x.글);
    if (!r.안전) 적기(x.이름, `기계 목록: ${r.걸린말.join(', ')}`);
    const k = 곁가지(x.글);
    if (k.붙음) 적기(x.이름, `뉴스 곁가지: ${k.어디}`);
  }
  const [일반, 피해자] = await Promise.all([부르기(검사물음(묶음)), 부르기(피해자물음(묶음))]);
  for (const [이름, v] of 판정읽기(일반)) if (v.답 === '고칠것') 적기(이름, v.까닭 || '나가면 안 되는 것');
  for (const [이름, v] of 판정읽기(피해자)) if (v.답 === '고칠것') 적기(이름, `피해자의 눈: ${v.까닭 || '괴로운 글'}`);
  return 걸림;
}

/* ── 출제·채굴할 기사를 고르는 자리 ─────────────────────────────
   범죄·참사가 중심인 기사는 문제·힌트의 재료로 쓰지 않는다. 거기서 «중심 사실» 을 물으면
   그 자체가 사건을 퀴즈로 만드는 일이 된다. 기사 제목·요약만 보고 기계로 가른다. */
const 아픈기사꼴 = /살인|살해|피살|참사|숨져|숨진|사망사고|유족|희생자|성범죄|성폭력|성폭행|성착취|아동학대|학대치사|흉기|묻지마|투신|극단적 선택|실종|추락사|폭행치사/;

/** 이 기사를 문제·힌트의 재료로 써도 되는가 (제목·부제·요약을 본다) */
function 재료로써도되나(기사) {
  const t = [기사?.title, 기사?.subtitle, 기사?.summary].filter(Boolean).join(' ');
  const m = t.match(아픈기사꼴);
  if (m) return { 된다: false, 까닭: m[0] };
  // 특정 사건 이름·참혹한 장면을 그리는 말이 제목에 있어도 재료로 쓰지 않는다
  const 걸린말 = [...사건, ...참혹].find(w => t.includes(w));
  return { 된다: !걸린말, 까닭: 걸린말 || '' };
}

