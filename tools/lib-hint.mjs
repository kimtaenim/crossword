/* 힌트를 쓰는 도구가 함께 쓰는 규칙과 난이도 잣대.
   안전(lib-safety.mjs)이 «나가면 안 되는 것» 이라면, 여기는 «풀 만한가, 그림이 그려지는가» 다.
   도구마다 제 말로 적어 두면 한쪽만 바뀐다 — 곁가지를 뗄 때 다시 쓰는 도구들이 «뜻만 적으라» 고만
   해서 «레버리지 — 빚을 지렛대 삼아 제 돈보다 크게 투자하는 것» 같은 사전 풀이가 남았다. */
import fs from 'fs';

/** 힌트를 쓰게 하는 모든 물음 끝에 붙인다 */
export function 힌트규칙() {
  return `[맥락 — 뜻 하나에 장면 하나]
사전 뜻풀이로만 끝내지 않는다. 뜻을 적고, 그 말이 쓰이는 장면을 하나 붙인다.
- 좋은 장면: 누구나 겪어 봤거나 들어 봤을 일, 숫자 하나로 보이는 예, 널리 알려진 흐름
  «레버리지 — 1억 들고 4억을 빌려 5억짜리 집을 사듯, 빚으로 판을 키우는 것»
  «실질임금 — 월급은 3% 올랐는데 물가가 4% 오르면 깎인 셈이 되는 그것»
- 나쁜 장면: 기사 한 건에만 나온 일, 사람 이름, 사건 이름 («○○ 논의에서 나온, …»)
  그 기사를 안 읽은 사람에게는 걸림돌이고, 피해자가 있는 사건이면 상처가 된다.
- 장면을 붙일 수 없으면 뜻만 두되, 한자어를 늘어놓지 말고 쉬운 말로.`;
}

/* 길고 드문 말은 너무 어렵다(«비경제활동인구» 는 기사 1100건에 두 번).
   글자가 길수록 기사에 더 자주 나온 말이라야 단어장에 넣는다.
   편집국이 꼭 살리고 싶은 말은 packs/살린말.txt 에 적는다. */
const 하한 = [[7, 8], [6, 3]];   // [글자 수 이상, 기사 수 이상]

let 살린말 = null;
function 살린말들() {
  if (살린말) return 살린말;
  try {
    살린말 = new Set(fs.readFileSync(new URL('../packs/살린말.txt', import.meta.url), 'utf8')
      .split(/\r?\n/).map(l => l.trim()).filter(l => l && !l.startsWith('#')));
  } catch (_) { 살린말 = new Set(); }
  return 살린말;
}

/** 길고 드물어 너무 어려운 말인가 */
export function 너무어려운가(낱말, 기사수) {
  if (살린말들().has(낱말)) return { 어렵다: false, 까닭: '' };
  for (const [길이, 최소] of 하한) {
    if (낱말.length >= 길이) {
      return 기사수 < 최소
        ? { 어렵다: true, 까닭: `${낱말.length}글자인데 기사 ${기사수}건 (${최소}건 이상이어야)` }
        : { 어렵다: false, 까닭: '' };
    }
  }
  return { 어렵다: false, 까닭: '' };
}
